"""The original delivery shares the issue claim's remote CAS cell."""
from typing import Protocol, runtime_checkable
from ..domain.claim import Claim
from ..domain.original_delivery import DockerCustody, OriginalDelivery
from ..domain.session_run import SessionRunAssets


@runtime_checkable
class OriginalDeliveryClaims(Protocol):
    def original_claim(self, issue_number: int) -> tuple[Claim, str]: ...
    def bind_original(self, issue_number: int, lease_id: str, fence: str, owner: OriginalDelivery) -> bool: ...
    def transition_original(self, issue_number: int, lease_id: str, fence: str, operation: str, *,
                            request_id: str, pr_number: int = 0, head_sha: str = "", base_sha: str = "", feedback: str = "") -> Claim | None: ...
    def renew_claim(self, issue_number: int, lease_id: str) -> bool: ...
    def reserve_original_launch(self, issue_number: int, request_id: str) -> bool: ...
    def bind_original_run(self, issue_number: int, request_id: str, run: SessionRunAssets, terminal_id: str) -> bool: ...
    def resume_original(self, issue_number: int, lease_id: str, fence: str,
                        identity: tuple[str, int, str]) -> bool: ...
    def bind_original_processes(self, issue_number: int, lease_id: str, fence: str,
                                roots: tuple[tuple[str, int, str, int, str], ...]) -> bool: ...


@runtime_checkable
class DockerOriginalDeliveryClaims(Protocol):
    def bind_original_docker_custody(self, issue_number: int, lease_id: str, fence: str,
                                    custody: tuple[DockerCustody, ...]) -> bool: ...
